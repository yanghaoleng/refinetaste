def revise(course):
    for q in course.questions:
        if q['id'] in REVISIONS:
            title, brief, prompt, followups = REVISIONS[q['id']]
            q.update(title=title, brief=brief or q['brief'], prompt=prompt, followUps=followups)
            q['variants'] = [dict(id='alternate', title=title, prompt=prompt)]
            q['reference'] = '先回应主问即可，选用追问不必答全。' + q['reference']
            q['rule'] = q['reference']
            q['rubric'] = ['回应主问中的具体经历或情境，可用虚构例子', '理由与实际条件相称，选用追问不作为必答清单', '尊重健康安全、同意与边界；允许不知道、拒绝或暂不做']

